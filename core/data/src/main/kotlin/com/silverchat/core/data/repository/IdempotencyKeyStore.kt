package com.silverchat.core.data.repository

import java.util.UUID
import java.util.concurrent.ConcurrentHashMap
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Хранилище ключей идемпотентности для операций, **поглощающих сущность**.
 *
 * ── Проблема, которую решает ────────────────────────────────────────────
 * Ключ, созданный внутри вызова репозитория, живёт ровно столько же, сколько
 * вызов. Но самый опасный сценарий двойного списания происходит МЕЖДУ
 * вызовами: запрос ушёл, сервер списал сильверы, ответ не дошёл, пользователь
 * увидел «Нет соединения» и нажал «Повторить». Второй вызов сгенерировал бы
 * новый ключ, и сервер выполнил бы покупку ещё раз — формально корректно,
 * потому что два разных ключа означают два разных намерения.
 *
 * Здесь ключ привязан к намерению, а не к вызову: пока намерение живо, все
 * попытки уходят с одним ключом.
 *
 * ── Почему это безопасно не для всех операций ───────────────────────────
 * Стабильный ключ означает, что повтор в пределах окна считается тем же
 * действием. Для операции, поглощающей цель, это верно по построению:
 * купленный лот нельзя купить второй раз, полученный за сегодня стрик —
 * получить ещё раз, принятый оффер — принять повторно. Повтор здесь
 * физически не может быть новым намерением.
 *
 * Для операций, которые законно повторяются (два одинаковых перевода подряд,
 * два одинаковых подарка), стабильный ключ проглотил бы второе действие,
 * поэтому они его не используют: там ключ создаётся на вызов, а защита от
 * потерянного ответа — автоматический повтор внутри одного вызова
 * (`apiCallIdempotent` в `:core:network`).
 *
 * ── Время жизни ─────────────────────────────────────────────────────────
 * [TTL_MS] — 10 минут: достаточно, чтобы пользователь успел повторить после
 * обрыва связи, и достаточно мало, чтобы ключ не пережил смену контекста.
 * Сервер хранит соответствие ключа результату не менее 24 часов
 * (`backend-contract/01-overview.md`), поэтому клиентское окно заведомо короче
 * серверного — обратное соотношение означало бы, что клиент может послать
 * «свежий» ключ, который сервер уже считает использованным.
 *
 * Ключ сбрасывается досрочно через [forget], как только исход стал
 * определённым: держать его дальше бессмысленно, а при покупке того же лота
 * на следующий день он и так будет другим.
 */
@Singleton
internal class IdempotencyKeyStore @Inject constructor() {

    private class Entry(val key: String, val expiresAt: Long)

    private val entries = ConcurrentHashMap<String, Entry>()

    /**
     * Возвращает ключ для намерения [intent], создавая его при первом обращении.
     *
     * Повторный вызов с тем же [intent] в пределах [TTL_MS] отдаёт ТОТ ЖЕ ключ —
     * это и есть защита от двойного выполнения.
     *
     * [intent] обязан описывать намерение, а не параметры запроса: обычно это
     * операция и идентификатор поглощаемой сущности, например
     * `market.buy:listing_42`.
     */
    fun keyFor(intent: String): String {
        purgeExpired()
        val now = System.currentTimeMillis()
        val entry = entries.compute(intent) { _, existing ->
            existing?.takeIf { it.expiresAt > now }
                ?: Entry(UUID.randomUUID().toString(), now + TTL_MS)
        }
        /* `ConcurrentHashMap.compute` возвращает null, только если null вернула
         * функция отображения; наша всегда отдаёт `Entry`. Проверка нужна
         * компилятору, а не логике — и она же ловит будущую правку, которая
         * начнёт удалять запись из-под `compute`. */
        return checkNotNull(entry) { "IdempotencyKeyStore: compute вернул null для «$intent»" }.key
    }

    /**
     * Сбрасывает ключ намерения после определённого исхода.
     *
     * Вызывается при успехе и при ошибках, которые исключают «действие
     * выполнилось, а ответ потерялся»: `InsufficientFunds`, `Validation`,
     * `Conflict`, `NotFound`. НЕ вызывается при сетевых и серверных ошибках —
     * именно там ключ и нужен для повтора.
     */
    fun forget(intent: String) {
        entries.remove(intent)
    }

    /** Сбрасывает все ключи — при смене аккаунта. */
    fun reset() = entries.clear()

    /* Очистка по размеру, а не по таймеру: отдельная корутина-чистильщик ради
     * словаря, который в норме держит не больше десятка записей, — это
     * зависимость от CoroutineScope и лишний повод для утечки. Записи всё
     * равно считаются протухшими при чтении, а порог нужен лишь затем, чтобы
     * словарь не рос бесконечно при долгой жизни процесса. */
    private fun purgeExpired() {
        if (entries.size < PURGE_THRESHOLD) return
        val now = System.currentTimeMillis()
        entries.entries.removeAll { it.value.expiresAt <= now }
    }

    companion object {

        /**
         * Ключ для операции, которую законно повторить.
         *
         * Создаётся заново на каждый вызов и НЕ запоминается: два одинаковых
         * перевода подряд — это два намерения, и стабильный ключ молча
         * проглотил бы второе. От потерянного ответа такую операцию страхует
         * автоматический повтор внутри одного вызова (`apiCallIdempotent`),
         * где ключ захвачен замыканием и поэтому остаётся прежним.
         *
         * Вынесен сюда, а не оставлен как `UUID.randomUUID().toString()` в
         * репозиториях, чтобы выбор стратегии был виден по имени вызова.
         */
        fun freshKey(): String = UUID.randomUUID().toString()

        /** Окно, в пределах которого повтор считается тем же намерением. */
        internal const val TTL_MS = 10 * 60 * 1000L

        /** Размер словаря, при котором запускается очистка протухших записей. */
        private const val PURGE_THRESHOLD = 64
    }
}
