package com.silverchat.core.network

/**
 * Словарь HTTP-заголовков протокола SilverChat.
 *
 * ── Зачем отдельный объект ──────────────────────────────────────────────
 * Одни и те же имена нужны в трёх местах: `AuthInterceptor` (каждый
 * REST-запрос), `OkHttpRealtimeSocket` (рукопожатие WebSocket) и сервер.
 * Строковые литералы в каждом из них разъезжаются незаметно: опечатка в
 * `X-SC-Protocol` не ломает сборку, но сервер перестаёт видеть версию
 * клиента и не может корректно отклонить устаревшее приложение.
 *
 * Нормативное описание каждого заголовка — в
 * `backend-contract/01-overview.md`, раздел «Заголовки».
 */
object HttpHeaders {

    /** Стандартный заголовок авторизации. Значение: `Bearer <access_token>`. */
    const val AUTHORIZATION = "Authorization"

    /**
     * Версия протокола.
     *
     * Передаётся и в REST, и в рукопожатии WebSocket. Сервер сравнивает её со
     * значением в поле `v` кадра и в `AuthPayload.protocol`; при
     * несовпадении обязан ответить `session.auth.fail` с кодом
     * `protocol_version_unsupported`, а не закрывать соединение молча.
     */
    const val PROTOCOL_VERSION = "X-SC-Protocol"

    /**
     * Платформа клиента: `android`.
     *
     * Нужна серверу для маршрутизации push-уведомлений: одному пользователю
     * может принадлежать несколько устройств разных платформ, и FCM-токен
     * Android бессмысленно отправлять на iOS.
     */
    const val PLATFORM = "X-SC-Platform"

    /**
     * Стабильный идентификатор установки — в REST-запросах.
     *
     * Значение генерируется один раз и хранится в `EncryptedSharedPreferences`
     * (`:core:data/device/DeviceIdentity`), поэтому переустановка приложения
     * даёт новый идентификатор и старая сессия перестаёт быть «текущей».
     *
     * В рукопожатии WebSocket тот же смысл несёт поле `device_id` в
     * `AuthPayload` — заголовок там не нужен, потому что сокет авторизуется
     * первым кадром, а не каждым запросом.
     */
    const val DEVICE_ID = "X-SC-Device-Id"

    /** Версия приложения: `APP_VERSION_NAME`. Используется для feature flags. */
    const val APP_VERSION = "X-SC-App-Version"

    /**
     * Ключ идемпотентности для операций, двигающих серебро.
     *
     * Повтор запроса с тем же ключом возвращает первоначальный результат, а не
     * выполняет операцию дважды. Сервер хранит соответствие не менее 24 часов,
     * в привязке к `user_id`.
     *
     * ── Почему заголовок, а не поле тела ────────────────────────────────
     * Ключ относится к транспорту, а не к домену: он не описывает покупку, а
     * позволяет серверу опознать повтор. В теле его пришлось бы повторять в
     * каждом DTO и в каждой JSON-схеме, а в заголовке он объявлен один раз и
     * проверяется одним middleware до разбора тела.
     *
     * ── Почему ключ создаёт репозиторий, а не интерцептор ───────────────
     * Интерцептор видел бы только один `Call` и мог бы сгенерировать лишь
     * новый ключ на каждый запрос. Но опасный сценарий происходит МЕЖДУ
     * вызовами: запрос ушёл, сервер списал деньги, ответ потерялся,
     * пользователь нажал «Повторить». Второй вызов — новый `Call`, и
     * интерцептор дал бы ему новый ключ, то есть защита не сработала бы
     * ровно там, где нужна. Поэтому решение о том, считать ли повтор тем же
     * намерением, принимает слой, который знает контекст операции, —
     * `IdempotencyKeyStore` в `:core:data`.
     *
     * Для отправки сообщений роль ключа играет `client_message_id` — он
     * передаётся в теле и дедуплицируется на стороне сервера, поэтому
     * отдельный заголовок там не нужен.
     *
     * Список операций и две стратегии выбора ключа — в
     * `backend-contract/02-rest-api.md`, раздел «Идемпотентность».
     */
    const val IDEMPOTENCY_KEY = "Idempotency-Key"

    /** Значение [PLATFORM] для этой сборки. */
    const val PLATFORM_ANDROID = "android"
}
