package com.silverchat.feature.chats

/**
 * Режимы экранов фичи «Чаты», общие для ViewModel, экранов и навигации.
 *
 * Вынесены в отдельный файл пакета фичи (а не в `navigation`), потому что
 * их используют три слоя: `NewChatViewModel` хранит режим в состоянии,
 * экраны ветвят по нему разметку, а навигация передаёт его при регистрации
 * графа. Если бы они жили в `navigation`, ViewModel зависел бы от
 * навигационного пакета — лишняя связь внутри одной фичи.
 */

/** Вкладка информационной панели чата. */
enum class ChatInfoTab {
    /** Описание, статистика, уведомления, управление. */
    INFO,

    /** Список участников с ролями. */
    MEMBERS,

    /** Защищённые пригласительные ссылки. */
    INVITES,

    /** Общие медиа по категориям. */
    MEDIA,
}

/**
 * Режим экрана «новый чат».
 *
 * Один экран обслуживает два сценария, потому что оба состоят из
 * «поиск людей → мультивыбор → подтверждение» и различаются только
 * последним шагом.
 */
enum class NewChatMode {
    /** Создание группы или канала. */
    CREATE,

    /** Выбор получателей для пересылки сообщений. */
    FORWARD_PICKER,
}
